"""Build extension/sr-models.js (spec format, base64 little-endian float16) from third-party sources.

  python3 -I dev/sr/tools/build_models.py [--extra model.json ...]

Shipped ids -> sources are in SHIPPED below. Adding/replacing a model is data-only: either add a row
here, or pass --extra <json> files containing spec-format entries (same fields as sr-models.js;
an --extra entry with an existing id replaces it). The runtime also resolves duplicate ids
last-one-wins, so a later script can override an entry without touching this file.
"""
import argparse
import base64
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from parse_artcnn import parse_artcnn  # noqa: E402
from parse_tf_pb import parse_fsrcnn  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
TP = os.path.join(ROOT, 'dev', 'sr', 'third_party')
OUT = os.path.join(ROOT, 'extension', 'sr-models.js')

ART_URL = 'https://github.com/Artoriuz/ArtCNN'
ART_COMMIT = '0837e5326e710f49e2ab0a8d995da0708047442e'
FSR_URL = 'https://github.com/Saafke/FSRCNN_Tensorflow'
FSR_COMMIT = '6a4812c4ef1c4f5947d79beafa32a05a6eb4a94d'

SOURCES = {
    'artcnn_c4f16_ds': dict(load=lambda: parse_artcnn(os.path.join(TP, 'ArtCNN', 'ArtCNN_C4F16_DS.glsl')),
                            base='none',
                            license='MIT; ArtCNN C4F16_DS, %s/blob/%s/GLSL/ArtCNN_C4F16_DS.glsl' % (ART_URL, ART_COMMIT)),
    'artcnn_c4f16': dict(load=lambda: parse_artcnn(os.path.join(TP, 'ArtCNN', 'ArtCNN_C4F16.glsl')),
                         base='none',
                         license='MIT; ArtCNN C4F16, %s/blob/%s/GLSL/ArtCNN_C4F16.glsl' % (ART_URL, ART_COMMIT)),
    'fsrcnn': dict(load=lambda: parse_fsrcnn(os.path.join(TP, 'FSRCNN_Tensorflow', 'FSRCNN_x2.pb')),
                   base='none',
                   license='Apache-2.0; FSRCNN x2 (56-12-4), %s/blob/%s/models/FSRCNN_x2.pb' % (FSR_URL, FSR_COMMIT)),
    'fsrcnn_small': dict(load=lambda: parse_fsrcnn(os.path.join(TP, 'FSRCNN_Tensorflow', 'FSRCNN-small_x2.pb')),
                         base='none',
                         license='Apache-2.0; FSRCNN-small x2 (32-5-1), %s/blob/%s/models/FSRCNN-small_x2.pb' % (FSR_URL, FSR_COMMIT)),
}

# id, label, content, tier, source
SHIPPED = [
    ('tsr-live-fast', 'Live action · Fast', 'live', 'fast', 'fsrcnn_small'),
    ('tsr-live-quality', 'Live action · Quality', 'live', 'quality', 'fsrcnn'),
    # No permissive anime port fits the 4.5k fast budget (smallest ArtCNN is 12.2k), so the anime
    # fast tier aliases the generic FSRCNN-small weights until a custom model replaces it.
    ('tsr-anime-fast', 'Anime · Fast', 'anime', 'fast', 'fsrcnn_small'),
    ('tsr-anime-quality', 'Anime · Quality', 'anime', 'quality', 'artcnn_c4f16_ds'),
]


def b64f16(a):
    a = np.asarray(a, dtype=np.float32)
    h = a.astype('<f2')
    if not np.all(np.isfinite(h)):
        raise ValueError('weight overflows float16')
    return base64.b64encode(h.tobytes()).decode('ascii')


def macs(layers):
    return int(sum(l['k'] * l['k'] * l['cin'] * l['cout'] for l in layers))


def layers_js(layers):
    out = []
    for l in layers:
        assert l['w'].shape == (l['cout'], l['cin'], l['k'], l['k'])
        d = {'k': l['k'], 'cin': l['cin'], 'cout': l['cout'], 'act': l['act']}
        if l.get('skip') is not None:
            d['skip'] = int(l['skip'])
        d['w'] = b64f16(l['w'])
        d['b'] = b64f16(l['b'])
        if l['act'] == 'prelu':
            d['alpha'] = b64f16(l['alpha'])
        out.append(d)
    return out


def js_value(v, indent=''):
    return json.dumps(v, separators=(', ', ': ')).replace('"', "'")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--extra', nargs='*', default=[], help='JSON files with spec-format model entries')
    ap.add_argument('--out', default=OUT)
    args = ap.parse_args()

    used = []
    for _, _, _, _, src in SHIPPED:
        if src not in used:
            used.append(src)
    var_names = {s: 'L_' + s for s in used}
    lines = [
        '// TrueHDR super-resolution models (spec: docs/SR_SPEC.md). GENERATED by dev/sr/tools/build_models.py',
        '// from dev/sr/third_party/* -- do not edit weights by hand. Weights: base64 little-endian float16,',
        '// layout [cout][cin][k][k]. Ids sharing a layers array alias the same weights.',
        '(function () {',
        "  'use strict';",
        '  var M = (globalThis.__TRUEHDR_SR_MODELS__ = globalThis.__TRUEHDR_SR_MODELS__ || []);',
    ]
    meta = {}
    for s in used:
        layers = SOURCES[s]['load']()
        meta[s] = macs(layers)
        rows = ',\n'.join('    { ' + ', '.join('%s: %s' % (k, js_value(v)) for k, v in d.items()) + ' }'
                          for d in layers_js(layers))
        lines.append('  var %s = [\n%s\n  ];' % (var_names[s], rows))
    entries = []
    for mid, label, content, tier, src in SHIPPED:
        e = {'id': mid, 'label': label, 'content': content, 'tier': tier, 'scale': 2,
             'base': SOURCES[src]['base'], 'macsPerPixel': meta[src], 'license': SOURCES[src]['license']}
        entries.append((mid, '  M.push({ ' + ', '.join('%s: %s' % (k, js_value(v)) for k, v in e.items())
                        + ', layers: %s });' % var_names[src]))
    for path in args.extra:
        data = json.load(open(path))
        for e in (data if isinstance(data, list) else [data]):
            entries = [x for x in entries if x[0] != e['id']]
            entries.append((e['id'], '  M.push(%s);' % json.dumps(e)))
    lines += [x[1] for x in entries]
    lines.append('})();')
    text = '\n'.join(lines) + '\n'
    with open(args.out, 'w') as f:
        f.write(text)
    print('wrote %s (%d bytes)' % (args.out, len(text.encode())))
    for mid, label, content, tier, src in SHIPPED:
        print('  %-18s %-14s MAC/px=%d' % (mid, src, meta[src]))


if __name__ == '__main__':
    main()
