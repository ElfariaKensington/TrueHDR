#!/usr/bin/env python3
"""Export trained checkpoints to the SR_SPEC model file and verify the f16 weights.

  python export.py --model tsr-live-fast=fast:runs/full/f12x5/latest.pt \
                   --model tsr-live-quality=quality:runs/full/q16x6/latest.pt \
                   --out export/tsr-live-models.js

Checks (on real DIV2K-valid frames, full resolution, clean + degraded variants):
  1. f16-rounded weights (as decoded from the written file) vs the PyTorch f32 checkpoint,
     both computed in f32: max |diff| must be <= 2/255  (hard requirement, exit 1 otherwise).
  2. Informational: the same f16 weights with f16 activations (MPS half) vs f32 reference.
"""
import argparse, json, os, sys

import torch

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from srmodel import load_ckpt, to_export, from_export, load_js  # noqa: E402
from data_loader import load_eval_set  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
LICENSE = 'MIT (custom-trained, TrueHDR)'
LABELS = {'fast': 'Live action · Fast', 'quality': 'Live action · Quality'}
TOL = 2 / 255


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--model', action='append', required=True, help='id=tier:checkpoint')
    ap.add_argument('--out', default=os.path.join(HERE, 'export', 'tsr-live-models.js'))
    ap.add_argument('--content', default='live')
    ap.add_argument('--check-images', type=int, default=6)
    ap.add_argument('--data', default=os.path.join(HERE, 'data', 'gen', 'valid'))
    a = ap.parse_args()

    entries = []
    for spec in a.model:
        mid, rest = spec.split('=', 1)
        tier, path = rest.split(':', 1)
        m, st = load_ckpt(path)
        for i, L in enumerate(m.spec):
            assert L['cout'] % 4 == 0 and (i == 0 or L['cin'] % 4 == 0), f'{mid}: channels not multiple of 4'
        budget = {'fast': 4500, 'quality': 12000}[tier]
        assert m.macs <= budget, f'{mid}: {m.macs} MAC/px > {tier} budget {budget}'
        d = to_export(m, id=mid, label=LABELS.get(tier, mid), content=a.content, tier=tier, license=LICENSE)
        # key order as in the spec
        order = ['id', 'label', 'content', 'tier', 'scale', 'base', 'macsPerPixel', 'license', 'layers']
        entries.append(({k: d[k] for k in order}, m, st.get('step')))

    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, 'w') as f:
        f.write('// TrueHDR custom-trained live-action SR models (generated by training/export.py; do not edit).\n')
        f.write('// Format: docs/SR_SPEC.md. Weights: base64 little-endian float16, layout [cout][cin][k][k].\n')
        f.write('globalThis.__TRUEHDR_SR_MODELS__ = (globalThis.__TRUEHDR_SR_MODELS__ || []);\n')
        for d, _, _ in entries:
            f.write('globalThis.__TRUEHDR_SR_MODELS__.push(' + json.dumps(d, ensure_ascii=True, separators=(',', ':')) + ');\n')
    size = os.path.getsize(a.out)
    print(f'wrote {a.out} ({size / 1024:.1f} KB)')

    # ---- numerical check, using the weights decoded back from the written file ----
    parsed = {d['id']: d for d in load_js(a.out)}
    dev = torch.device('mps' if torch.backends.mps.is_available() else 'cpu')
    imgs = load_eval_set(a.data, variants=[0, 1], limit=a.check_images // 2 or 1)
    ok = True
    for d, m32, step in entries:
        m16w = from_export(parsed[d['id']])
        ref, w16 = m32.to(dev), m16w.to(dev)
        e_w, e_act = 0.0, 0.0
        with torch.no_grad():
            for s in imgs:
                x = torch.from_numpy(s['lr']).float().div(255)[None, None].to(dev)
                y_ref = ref(x)
                e_w = max(e_w, (w16(x) - y_ref).abs().max().item())
                h = w16.half()
                y_h = (h.residual(x.half()).float() + torch.nn.functional.interpolate(
                    x, scale_factor=2, mode='bicubic', align_corners=False))
                w16.float()
                e_act = max(e_act, (y_h - y_ref).abs().max().item())
        status = 'OK' if e_w <= TOL else 'FAIL'
        ok &= e_w <= TOL
        print(f"{d['id']}: step={step} macs/px={d['macsPerPixel']} layers={len(d['layers'])} "
              f"| f16-weights max|diff| = {e_w * 255:.3f}/255 [{status}, tol 2/255] "
              f"| f16 weights+activations max|diff| = {e_act * 255:.3f}/255 (info)")
    if size >= 250 * 1024:
        print('WARNING: file >= 250 KB (spec total budget for all models)')
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
